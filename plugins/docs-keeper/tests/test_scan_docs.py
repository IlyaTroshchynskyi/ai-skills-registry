def mentions_by_name(report: dict[str, Any]) -> dict[str, list[tuple[str, str]]]:
    return {entry["name"]: [(mention["file"], mention["kind"]) for mention in entry["mentions"]]
            for entry in report["stale_mentions"]}


def kinds_and_targets(problems: list[dict[str, Any]]) -> set[tuple[str, str]]:
    return {(problem["kind"], problem["target"]) for problem in problems}


def orphan_files(problems: list[dict[str, Any]]) -> set[str]:
    return {problem["file"] for problem in problems if problem["kind"] == "orphan"}


