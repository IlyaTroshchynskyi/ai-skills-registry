def test_links_takes_paths_from_the_repository_root(repo: Path) -> None:
    write(repo / "README.md", "# App\n\n[gone](docs/missing.md)\n")

    from_subfolder = run_script("links", "README.md", cwd=repo / "src")
    mistyped = run_script("links", "READMe.md", cwd=repo)

    assert [problem["kind"] for problem in json.loads(from_subfolder.stdout)] == ["broken_link"]
    assert json.loads(mistyped.stdout) == [{"file": "READMe.md", "line": 0, "kind": "not_a_document", "target": ""}]


